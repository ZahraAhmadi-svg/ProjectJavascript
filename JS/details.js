    /* =====================================================
       FAVORITE
    ====================================================== */

    function setupFavorite(storyId) {

        const button =
            document.getElementById(
                "detailFavoriteBtn"
            );


        if (!button) return;


        updateFavoriteButton(
            button,
            storyId
        );


        button.addEventListener(
            "click",
            function () {

                if (
                    typeof getCurrentUser ===
                    "function" &&
                    !getCurrentUser()
                ) {

                    if (
                        typeof requireLogin ===
                        "function"
                    ) {

                        requireLogin(
                            `details.html?id=${storyId}`
                        );

                    }

                    return;
                }


                let favorites =
                    JSON.parse(
                        localStorage.getItem(
                            "favoriteStories"
                        )
                    ) || [];


                if (
                    favorites.includes(
                        storyId
                    )
                ) {

                    favorites =
                        favorites.filter(
                            id => id !== storyId
                        );

                } else {

                    favorites.push(
                        storyId
                    );

                }


                localStorage.setItem(
                    "favoriteStories",
                    JSON.stringify(
                        favorites
                    )
                );


                updateFavoriteButton(
                    button,
                    storyId
                );

            }
        );

    }



    /* =====================================================
       UPDATE FAVORITE
    ====================================================== */

    function updateFavoriteButton(
        button,
        storyId
    ) {

        const icon =
            button.querySelector("i");


        const favorites =
            JSON.parse(
                localStorage.getItem(
                    "favoriteStories"
                )
            ) || [];


        if (
            favorites.includes(storyId)
        ) {

            button.classList.add(
                "favorite-active"
            );

            icon.className =
                "bi bi-heart-fill";

        } else {

            button.classList.remove(
                "favorite-active"
            );

            icon.className =
                "bi bi-heart";

        }

    }



